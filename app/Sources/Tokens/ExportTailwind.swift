import Foundation

/// Tailwind CSS v3 theme as a `tailwind.config.js`, with the values under `theme.extend`.
/// Sources:
/// - https://v3.tailwindcss.com/docs/theme (theme.extend, spacing, borderRadius, fontFamily)
/// - https://v3.tailwindcss.com/docs/font-size (fontSize as [size, { lineHeight, letterSpacing, fontWeight }])
/// - https://v3.tailwindcss.com/docs/customizing-colors (colors)
///
/// A Tailwind name holds one value, so only the light values are written. Numbers have no Tailwind key and are skipped.
/// Names are the path joined with hyphens, cleaned to lower-case letters, digits and hyphens. Clashes get "-2", "-3" …
public enum TailwindExport {
    public static func config(_ set: TokenSet) -> String {
        var names = KebabNames()
        var colors: [String] = [], spacing: [String] = [], radius: [String] = []
        var fontSize: [String] = [], fontFamily: [String] = [], fontWeight: [String] = []
        var duration: [String] = [], easing: [String] = []

        for token in set.tokens {
            if case .number = token.value { continue }
            let key = names.name(for: token.path)
            switch token.value {
            case .color(let c):
                colors.append(entry(key, quoted(c.hex)))
            case .dimension(let x, let unit):
                let value = quoted(TokenExport.fmt(x) + unit)
                if token.path.first == "radius" {
                    radius.append(entry(key, value))
                } else {
                    spacing.append(entry(key, value))
                }
            case .typography(let t):
                let style = "[\(quoted(TokenExport.fmt(t.fontSize) + "px")), { lineHeight: \(quoted(TokenExport.fmt(t.lineHeight))), "
                    + "letterSpacing: \(quoted(TokenExport.fmt(t.letterSpacing) + "px")), fontWeight: \(quoted(String(t.fontWeight))) }]"
                fontSize.append(entry(key, style))
                fontFamily.append(entry(key, families(t.fontFamily)))
            case .fontFamily(let list):
                fontFamily.append(entry(key, families(list)))
            case .fontWeight(let w):
                fontWeight.append(entry(key, quoted(String(w))))
            case .duration(let ms):
                duration.append(entry(key, quoted(TokenExport.fmt(ms) + "ms")))
            case .cubicBezier(let a, let b, let c, let d):
                let curve = "cubic-bezier(\(TokenExport.fmt(a)), \(TokenExport.fmt(b)), \(TokenExport.fmt(c)), \(TokenExport.fmt(d)))"
                easing.append(entry(key, quoted(curve)))
            case .number:
                continue
            }
        }

        let extend = [
            block("colors", colors),
            block("spacing", spacing),
            block("borderRadius", radius),
            block("fontSize", fontSize),
            block("fontFamily", fontFamily),
            block("fontWeight", fontWeight),
            block("transitionDuration", duration),
            block("transitionTimingFunction", easing),
        ].flatMap { $0 }

        var lines = [
            "// Tailwind CSS v3 theme, generated by ALFAcolor. Do not edit by hand.",
            "// Sources: https://v3.tailwindcss.com/docs/theme, /docs/font-size, /docs/customizing-colors",
            "/** @type {import('tailwindcss').Config} */",
            "module.exports = {",
            "  theme: {",
        ]
        if extend.isEmpty {
            lines.append("    extend: {},")
        } else {
            lines.append("    extend: {")
            lines += extend
            lines.append("    },")
        }
        lines += ["  },", "}", ""]
        return lines.joined(separator: "\n")
    }

    // MARK: Helpers

    /// One `key: value,` line of an object literal.
    private static func entry(_ key: String, _ value: String) -> String {
        "\(quoted(key)): \(value),"
    }

    /// A named object such as `colors: { … }`, indented for `theme.extend`. Empty objects are left out.
    private static func block(_ name: String, _ entries: [String]) -> [String] {
        guard !entries.isEmpty else { return [] }
        return ["      \(name): {"] + entries.map { "        \($0)" } + ["      },"]
    }

    /// A list of font names, as Tailwind takes them: `['Inter', 'sans-serif']`.
    private static func families(_ names: [String]) -> String {
        "[" + names.map(quoted).joined(separator: ", ") + "]"
    }

    /// A JavaScript string in single quotes.
    private static func quoted(_ text: String) -> String {
        "'" + text.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "'", with: "\\'") + "'"
    }
}

/// Hands out Tailwind names: cleaned path, then the lowest free suffix when two paths give the same name.
struct KebabNames {
    private var taken: Set<String> = []

    mutating func name(for path: [String]) -> String {
        let base = KebabNames.clean(path.joined(separator: "-"))
        var candidate = base
        var number = 2
        while taken.contains(candidate) {
            candidate = "\(base)-\(number)"
            number += 1
        }
        taken.insert(candidate)
        return candidate
    }

    /// German umlauts folded to ASCII, as in the names of the design tokens.
    private static let folds: [Character: String] = ["\u{E4}": "a", "\u{F6}": "o", "\u{FC}": "u", "\u{DF}": "ss"]

    /// Lower-case ASCII letters and digits, with single hyphens between runs of anything else. Never empty.
    static func clean(_ text: String) -> String {
        var out = ""
        for character in text.lowercased() {
            if let folded = folds[character] {
                out += folded
            } else if character.isASCII && (character.isLetter || character.isNumber) {
                out.append(character)
            } else if out.last != "-" {
                out.append("-")
            }
        }
        while out.hasPrefix("-") { out.removeFirst() }
        while out.hasSuffix("-") { out.removeLast() }
        return out.isEmpty ? "token" : out
    }
}
