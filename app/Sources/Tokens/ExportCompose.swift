import Foundation

/// Jetpack Compose source (Kotlin): one `object` with the values of a token set.
/// Sources:
/// - https://developer.android.com/develop/ui/compose/graphics/draw/brush (Color(0xFF…), dp, sp)
/// - https://developer.android.com/develop/ui/compose/text/fonts (TextStyle with fontFamily, fontWeight, fontSize, lineHeight, letterSpacing)
///
/// Colors are `Color(0xAARRGGBB)`. Dimensions are `Dp` (a rem counts as 16). Text styles are `TextStyle` with `sp` units.
/// A font name that Compose does not know gets `FontFamily.Default` and a comment, because a font resource is needed.
/// The dark colors go to a second object `TokensDark`, with the same names. Numbers become `Double`; curves are skipped.
public enum ComposeExport {
    public static func kotlin(_ set: TokenSet, dark: TokenSet? = nil) -> String {
        let light = declarations(set.tokens)
        let darkColors = (dark?.tokens ?? []).filter { token in
            if case .color = token.value { return true }
            return false
        }
        let darkLines = darkColors.isEmpty ? [] : [""] + objectLines("TokensDark", declarations(darkColors))
        let body = objectLines("Tokens", light) + darkLines

        var lines = [
            "// Compose source, generated by ALFAcolor. Do not edit by hand.",
            "// Sources: https://developer.android.com/develop/ui/compose/graphics/draw/brush (Color, dp, sp)",
            "// https://developer.android.com/develop/ui/compose/text/fonts (TextStyle)",
            "",
        ]
        // Imports are added only for what the body uses, so the file compiles without unused imports.
        let text = body.joined(separator: "\n")
        let imports: [(String, String)] = [
            ("Color(", "import androidx.compose.ui.graphics.Color"),
            ("TextStyle(", "import androidx.compose.ui.text.TextStyle"),
            ("FontFamily.", "import androidx.compose.ui.text.font.FontFamily"),
            ("FontWeight(", "import androidx.compose.ui.text.font.FontWeight"),
            (".dp", "import androidx.compose.ui.unit.dp"),
            (".sp", "import androidx.compose.ui.unit.sp"),
        ]
        let used = imports.filter { text.contains($0.0) }.map(\.1)
        if !used.isEmpty {
            lines += used
            lines.append("")
        }
        lines += body
        return lines.joined(separator: "\n") + "\n"
    }

    // MARK: Declarations

    /// One block of lines per token, with a unique Kotlin name. Blocks are joined with an empty line between them.
    private static func declarations(_ tokens: [Token]) -> [[String]] {
        var taken: Set<String> = []
        return tokens.map { token -> [String] in
            let name = uniqueName(TokenExport.camel(token.path), taken: &taken)
            return declaration(name, token.value)
        }
    }

    private static func declaration(_ name: String, _ value: TokenValue) -> [String] {
        switch value {
        case .color(let c):
            return ["    val \(name) = Color(0x\(argb(c)))"]
        case .dimension(let x, let unit):
            return ["    val \(name) = \(TokenExport.fmt(unit == "rem" ? x * 16 : x)).dp"]
        case .number(let x):
            return ["    val \(name): Double = \(literal(x))"]
        case .duration(let ms):
            return ["    val \(name): Double = \(literal(ms)) // milliseconds"]
        case .fontFamily(let names):
            return fontComment(names) + ["    val \(name) = \(familyExpression(names))"]
        case .fontWeight(let w):
            return ["    val \(name) = FontWeight(\(w))"]
        case .typography(let t):
            return fontComment(t.fontFamily) + [
                "    val \(name) = TextStyle(",
                "        fontFamily = \(familyExpression(t.fontFamily)),",
                "        fontWeight = FontWeight(\(t.fontWeight)),",
                "        fontSize = \(TokenExport.fmt(t.fontSize)).sp,",
                "        letterSpacing = \(TokenExport.fmt(t.letterSpacing)).sp,",
                "        lineHeight = \(TokenExport.fmt(t.fontSize * t.lineHeight)).sp,",
                "    )",
            ]
        case .cubicBezier:
            return ["    // \(name): cubic-bezier is not exported to Compose yet"]
        }
    }

    // MARK: Fonts

    /// The Compose font for the first name, or nil when Compose has no such font.
    private static func builtInFamily(_ names: [String]) -> String? {
        let lower = (names.first ?? "").lowercased()
        if ["mono", "courier", "menlo", "code"].contains(where: lower.contains) { return "Monospace" }
        if lower.contains("cursive") { return "Cursive" }
        if lower.contains("serif") && !lower.contains("sans") { return "Serif" }
        if ["sans", "system"].contains(where: lower.contains) { return "SansSerif" }
        return nil
    }

    /// `FontFamily.SansSerif` for a built-in name, `FontFamily.Default` otherwise.
    private static func familyExpression(_ names: [String]) -> String {
        "FontFamily." + (builtInFamily(names) ?? "Default")
    }

    /// A comment above a font that needs a resource. Empty for the built-in fonts.
    private static func fontComment(_ names: [String]) -> [String] {
        guard builtInFamily(names) == nil, let first = names.first else { return [] }
        let name = first.replacingOccurrences(of: "\n", with: " ")
        return ["    // font \"\(name)\": Compose needs a font resource, FontFamily.Default is used"]
    }

    // MARK: Names and values

    /// Keeps the names unique: a clash gets the next number after the name.
    private static func uniqueName(_ base: String, taken: inout Set<String>) -> String {
        var name = keywordSafe(base)
        var number = 2
        while taken.contains(name) {
            name = keywordSafe("\(base)\(number)")
            number += 1
        }
        taken.insert(name)
        return name
    }

    private static let keywords: Set<String> = [
        "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface", "is",
        "null", "object", "package", "return", "super", "this", "throw", "true", "try", "typealias", "val", "var",
        "when", "while",
    ]

    private static func keywordSafe(_ name: String) -> String {
        keywords.contains(name) ? name + "Value" : name
    }

    /// The colour as an ARGB literal: alpha, red, green, blue, two hex digits each.
    private static func argb(_ c: RGB) -> String {
        [c.a, c.r, c.g, c.b].map { channel in
            String(format: "%02X", Int(min(max((channel * 255).rounded(), 0), 255)))
        }.joined()
    }

    /// A Kotlin Double literal: always with a decimal point.
    private static func literal(_ x: Double) -> String {
        let text = TokenExport.fmt(x)
        return text.contains(".") ? text : text + ".0"
    }

    private static func objectLines(_ name: String, _ declarations: [[String]]) -> [String] {
        guard !declarations.isEmpty else { return [] }
        return ["object \(name) {"] + declarations.flatMap { $0 } + ["}"]
    }
}
