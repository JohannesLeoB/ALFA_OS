import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

from data import load, root
from kb import rows

BUILD = root / "build"
SCHEMA_OUT = BUILD / "supabase_schema.sql"
SEED_OUT = BUILD / "supabase_seed.sql"
ORDER = ("sources", "concepts", "atoms", "library_entries", "media", "setups", "setup_values",
         "catalog_sections", "edges")


def literal(value):
    if value is None:
        return "null"
    if isinstance(value, int) and not isinstance(value, bool):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def schema():
    base = (root / "sql" / "schema.sql").read_text(encoding="utf-8")
    base = base.replace("create table if not exists ", "create table if not exists kb.")
    extra = (root / "sql" / "postgres.sql").read_text(encoding="utf-8")
    return "create schema if not exists kb;\n\n" + base + "\n" + extra


PART_BYTES = 40000
DUPLICATES = ("statement_en", "statement_de", "formula")


def statements(loaded):
    tables = rows(loaded)
    hidden = {entry["id"] for _, entry in loaded["library-entry"] if entry["sharing"] != "open"}
    result = [f"delete from kb.{table};" for table in reversed(ORDER)]
    for table in ORDER:
        if table == "edges":
            continue
        values = []
        for item in tables[table]:
            if table == "library_entries" and item[0] in hidden:
                continue
            if table == "atoms":
                record = {k: v for k, v in json.loads(item[-1]).items() if k not in DUPLICATES}
                item = item[:-1] + (json.dumps(record, ensure_ascii=False),)
            values.append("(" + ", ".join(literal(v) for v in item) + ")")
        head = f"insert into kb.{table} values\n"
        chunk = []
        for value in values:
            if chunk and sum(len(v) for v in chunk) + len(value) > PART_BYTES:
                result.append(head + ",\n".join(chunk) + ";")
                chunk = []
            chunk.append(value)
        if chunk:
            result.append(head + ",\n".join(chunk) + ";")
    result.append("select kb.rebuild_edges();")
    return result, len(hidden)


def main():
    BUILD.mkdir(exist_ok=True)
    SCHEMA_OUT.write_text(schema(), encoding="utf-8")
    parts, hidden = statements(load())
    header = "-- Generated by tools/export_supabase.py. Apply build/supabase_schema.sql first."
    SEED_OUT.write_text("\n".join([header, "begin;"] + parts + ["commit;"]) + "\n", encoding="utf-8")
    part_dir = BUILD / "supabase_seed_parts"
    part_dir.mkdir(exist_ok=True)
    for old in part_dir.glob("*.sql"):
        old.unlink()
    for number, part in enumerate(parts, 1):
        (part_dir / f"{number:02d}.sql").write_text(part + "\n", encoding="utf-8")
    print(f"Wrote {SCHEMA_OUT.relative_to(root)}, {SEED_OUT.relative_to(root)} and {len(parts)} parts. "
          f"Library entries with sharing setup_only are left out: {hidden}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
