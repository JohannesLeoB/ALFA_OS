import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

from data import load, root
from kb import rows

BUILD = root / "build"
SCHEMA_OUT = BUILD / "supabase_schema.sql"
SEED_OUT = BUILD / "supabase_seed.sql"
ORDER = ("sources", "concepts", "atoms", "library_entries", "media", "setups", "setup_values",
         "catalog_sections", "edges")


def literal(value):
    if value is None:
        return "null"
    if isinstance(value, int) and not isinstance(value, bool):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def schema():
    base = (root / "sql" / "schema.sql").read_text(encoding="utf-8")
    base = base.replace("create table if not exists ", "create table if not exists kb.")
    extra = (root / "sql" / "postgres.sql").read_text(encoding="utf-8")
    return "create schema if not exists kb;\n\n" + base + "\n" + extra


def seed(loaded):
    tables = rows(loaded)
    hidden = {entry["id"] for _, entry in loaded["library-entry"] if entry["sharing"] != "open"}
    lines = ["-- Generated by tools/export_supabase.py. Apply build/supabase_schema.sql first.", "begin;"]
    for table in reversed(ORDER):
        lines.append(f"delete from kb.{table};")
    for table in ORDER:
        for item in tables[table]:
            if table == "library_entries" and item[0] in hidden:
                continue
            if table == "edges" and (item[0] in hidden or item[2] in hidden):
                continue
            lines.append(f"insert into kb.{table} values ({', '.join(literal(v) for v in item)});")
    lines.append("commit;")
    return "\n".join(lines) + "\n", len(hidden)


def main():
    BUILD.mkdir(exist_ok=True)
    SCHEMA_OUT.write_text(schema(), encoding="utf-8")
    text, hidden = seed(load())
    SEED_OUT.write_text(text, encoding="utf-8")
    print(f"Wrote {SCHEMA_OUT.relative_to(root)} and {SEED_OUT.relative_to(root)}. "
          f"Library entries with sharing setup_only are left out: {hidden}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
