import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

from data import load, root
from kb import rows

OUT = root / "build" / "supabase_seed.sql"


def literal(value):
    if value is None:
        return "null"
    return "'" + str(value).replace("'", "''") + "'"


def main():
    loaded = load()
    tables = rows(loaded)
    hidden = {entry["id"] for _, entry in loaded["library-entry"] if entry["sharing"] != "open"}
    lines = ["-- Generated by tools/export_supabase.py. Run sql/schema.sql and sql/postgres.sql first.",
             "begin;"]
    for table in tables:
        lines.append(f"delete from {table};")
    for table, items in tables.items():
        for item in items:
            if table == "library_entries" and item[0] in hidden:
                continue
            if table == "edges" and (item[0] in hidden or item[2] in hidden):
                continue
            lines.append(f"insert into {table} values ({', '.join(literal(v) for v in item)});")
    lines.append("commit;")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT.relative_to(root)}. Library entries with sharing setup_only are left out: {len(hidden)}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
